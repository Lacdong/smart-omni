import { expect, test } from '@playwright/test'

async function login(page, role = 'owner') {
  await page.goto('/auth/login')
  await page.getByLabel('Email address').fill(`${role}@smartomni.demo`)
  await page.getByLabel('Password', { exact: true }).fill('Demo@123')
  await page.getByRole('button', { name: 'Sign in', exact: true }).click()
  await expect(page).toHaveURL(/\/merchant\/dashboard$/)
}

test('owner saves public store settings, discards drafts, and updates the storefront across tabs', async ({ page, context }) => {
  const errors = []
  page.on('pageerror', error => errors.push(error.message))
  await login(page)
  await page.goto('/merchant/settings/profile')
  await page.getByLabel('Store name', { exact: true }).fill('Updated Studio')
  await page.getByLabel('Contact email').fill('hello@example.com')
  await page.getByLabel('Store description').fill('Everyday objects, carefully selected.')
  await page.getByRole('button', { name: 'Save changes' }).click()
  await expect(page.getByRole('status')).toContainText('Changes saved')
  await page.reload()
  await expect(page.getByLabel('Store name', { exact: true })).toHaveValue('Updated Studio')
  await page.getByLabel('Store name', { exact: true }).fill('Unsaved name')
  await page.getByRole('button', { name: 'Discard changes' }).click()
  await expect(page.getByLabel('Store name', { exact: true })).toHaveValue('Updated Studio')
  const storefront = await context.newPage()
  await storefront.goto('/store/everyday-studio')
  await expect(storefront.getByRole('heading', { name: 'Updated Studio', exact: true })).toBeVisible()
  await expect(storefront.getByRole('link', { name: 'hello@example.com' })).toHaveAttribute('href', 'mailto:hello@example.com')
  await page.getByRole('link', { name: 'Appearance', exact: true }).click()
  await page.getByLabel('Storefront headline').fill('Thoughtful things for every day.')
  await page.getByLabel('Announcement', { exact: true }).fill('Welcome to our collection.')
  await page.getByLabel('Accent palette').selectOption('forest')
  await page.getByLabel('Catalog spacing').selectOption('compact')
  await page.getByRole('button', { name: 'Save changes' }).click()
  await expect(storefront.getByRole('heading', { name: 'Thoughtful things for every day.' })).toBeVisible()
  await expect(storefront.locator('[data-accent]')).toHaveAttribute('data-accent', 'forest')
  expect(await storefront.getByRole('region', { name: 'Products', exact: true }).evaluate(node => getComputedStyle(node).gap)).toBe('12px')
  await page.getByRole('link', { name: 'Store policies', exact: true }).click()
  await page.getByLabel('Shipping policy').fill('Shipping is confirmed by the selected marketplace.\nContact us for help.')
  await page.getByRole('button', { name: 'Save changes' }).click()
  await storefront.getByText('Shipping policy', { exact: true }).click()
  await expect(storefront.getByText('Shipping is confirmed by the selected marketplace.', { exact: false })).toBeVisible()
  await expect(storefront.getByText('Return policy', { exact: true })).toHaveCount(0)
  await page.evaluate(() => { document.activeElement?.blur(); window.scrollTo(0, 0) })
  await page.screenshot({ path: 'artifacts/merchant/settings-desktop.png', fullPage: true })
  expect(errors).toEqual([])
})

test('staff invitation acceptance, live permissions, suspension, revocation and protected settings', async ({ page, context }) => {
  await login(page)
  await page.goto('/merchant/team')
  await page.getByLabel('Staff email').fill(' STAFF@SMARTOMNI.DEMO ')
  await page.getByRole('button', { name: 'Create demo invitation' }).click()
  await expect(page.getByRole('status')).toContainText('No email was sent')
  await page.screenshot({ path: 'artifacts/merchant/team-desktop.png', fullPage: true })
  await page.getByLabel('Staff email').fill('staff@smartomni.demo')
  await page.getByRole('button', { name: 'Create demo invitation' }).click()
  await expect(page.getByRole('alert')).toContainText('already has a membership')
  const staff = await context.newPage()
  await login(staff, 'staff')
  await staff.goto('/merchant/settings/profile')
  await expect(staff).toHaveURL(/\/merchant\/dashboard$/)
  await expect(staff.getByRole('heading', { name: 'Your workspace is waiting.' })).toBeVisible()
  await staff.getByRole('link', { name: 'Check invitations' }).click()
  await staff.getByRole('button', { name: 'Accept demo invitation' }).click()
  await staff.getByRole('link', { name: 'Open workspace' }).click()
  await expect(staff.getByRole('heading', { name: 'Recent orders' })).toBeVisible()
  await expect(staff.getByRole('heading', { name: 'Inventory alerts' })).toHaveCount(0)
  await expect(staff.getByRole('button', { name: 'Export report' })).toHaveCount(0)
  await staff.goto('/merchant/team')
  await expect(staff).toHaveURL(/\/merchant\/dashboard$/)
  const member = page.getByRole('listitem').filter({ hasText: 'staff@smartomni.demo' })
  await member.getByLabel('View orders', { exact: true }).uncheck()
  await member.getByLabel('View inventory alerts').check()
  await member.getByRole('button', { name: 'Save permissions' }).click()
  await expect(staff.getByRole('heading', { name: 'Recent orders' })).toHaveCount(0)
  await expect(staff.getByRole('heading', { name: 'Inventory alerts' })).toBeVisible()
  await member.getByRole('button', { name: 'Suspend access' }).click()
  await page.getByRole('dialog').getByRole('button', { name: 'Cancel', exact: true }).click()
  await expect(staff.getByRole('heading', { name: 'Inventory alerts' })).toBeVisible()
  await member.getByRole('button', { name: 'Suspend access' }).click()
  await page.getByRole('dialog').getByRole('button', { name: 'Suspend access', exact: true }).click()
  await expect(staff.getByRole('heading', { name: 'Your staff access is suspended.' })).toBeVisible()
  await member.getByRole('button', { name: 'Restore access' }).click()
  await expect(staff.getByRole('heading', { name: 'Inventory alerts' })).toBeVisible()
  await member.getByRole('button', { name: 'Remove member' }).click()
  await page.getByRole('dialog').getByRole('button', { name: 'Remove member', exact: true }).click()
  await expect(staff.getByRole('heading', { name: 'Your workspace is waiting.' })).toBeVisible()
  await staff.reload()
  await expect(staff.getByRole('heading', { name: 'Your workspace is waiting.' })).toBeVisible()
  await page.reload()
  await expect(page.getByText('Access revoked', { exact: false })).toBeVisible()
})

test('revoked pending invitations cannot be accepted and suspended owners cannot edit settings', async ({ page, context }) => {
  await login(page)
  await page.goto('/merchant/team')
  await page.getByLabel('Staff email').fill('staff@smartomni.demo')
  await page.getByRole('button', { name: 'Create demo invitation' }).click()
  const staff = await context.newPage()
  await login(staff, 'staff')
  await staff.goto('/merchant/notifications')
  await expect(staff.getByRole('button', { name: 'Accept demo invitation' })).toBeVisible()
  await page.getByRole('button', { name: 'Revoke invitation' }).click()
  await page.getByRole('dialog').getByRole('button', { name: 'Revoke invitation', exact: true }).click()
  await expect(staff.getByRole('button', { name: 'Accept demo invitation' })).toHaveCount(0)
  await page.evaluate(() => { localStorage.setItem('smartomni.platform-demo.v1', JSON.stringify({ tenants: [{ id: 'demo-tenant', status: 'SUSPENDED' }] })); window.dispatchEvent(new Event('smartomni:platform-demo')) })
  await page.goto('/merchant/settings/profile')
  await expect(page).toHaveURL(/\/merchant\/dashboard$/)
  await expect(page.getByRole('heading', { name: 'Workspace access is paused.' })).toBeVisible()
})

test('settings and team remain usable on a narrow screen and report storage failures honestly', async ({ page }) => {
  await page.setViewportSize({ width: 375, height: 812 })
  await login(page)
  for (const route of ['profile', 'appearance', 'policies']) {
    await page.goto(`/merchant/settings/${route}`)
    await expect(page.getByRole('heading', { name: 'Store settings', exact: true })).toBeVisible()
    await expect(page.getByRole('button', { name: 'Save changes', exact: true })).toBeVisible()
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
    await page.screenshot({ path: `artifacts/merchant/${route}-mobile.png`, fullPage: true })
  }
  await page.getByLabel('Workspace page').selectOption('/merchant/team')
  await expect(page.getByRole('heading', { name: 'Team', exact: true })).toBeVisible()
  await page.screenshot({ path: 'artifacts/merchant/team-mobile.png', fullPage: true })
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await page.getByLabel('Staff email').fill('staff@smartomni.demo')
  await page.evaluate(() => { Storage.prototype.setItem = () => { throw new Error('Blocked storage') } })
  await page.getByRole('button', { name: 'Create demo invitation' }).click()
  await expect(page.getByRole('alert')).toContainText('Could not save')
  await expect(page.getByText('Invitation pending', { exact: false })).toHaveCount(0)
})
