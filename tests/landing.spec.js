import { expect, test } from '@playwright/test'

test('landing navigation, CTAs, and dashboard preview work', async ({ page }) => {
  const errors = []
  page.on('pageerror', error => errors.push(error.message))
  page.on('console', message => { if (message.type() === 'error') errors.push(message.text()) })
  await page.goto('/')
  await expect(page.getByRole('heading', { level: 1 })).toHaveText('One workspace for every sales channel.')
  const navigation = page.getByRole('navigation', { name: 'Main navigation' })
  await expect(navigation.getByRole('link')).toHaveCount(5)
  await expect(navigation.getByRole('link', { name: 'Sign in' })).toHaveCount(0)
  const logoBox = await page.getByRole('link', { name: 'SmartOmni home' }).first().boundingBox()
  const glassBox = await navigation.boundingBox()
  const signInBox = await page.locator('header').getByRole('link', { name: 'Sign in' }).boundingBox()
  expect(logoBox.x + logoBox.width).toBeLessThan(glassBox.x)
  expect(glassBox.x + glassBox.width).toBeLessThan(signInBox.x)
  const showcase = page.locator('section[aria-labelledby="showcase-title"]')
  const previousPreview = showcase.getByRole('button', { name: 'Previous preview' })
  const nextPreview = showcase.getByRole('button', { name: 'Next preview' })
  await expect(showcase.getByRole('tab')).toHaveCount(0)
  await expect(previousPreview).toBeDisabled()
  await expect(showcase.getByText('Preview 01 / 03')).toBeVisible()
  await nextPreview.click()
  await expect(showcase.locator('[aria-roledescription="slide"][aria-hidden="false"]')).toContainText('SP-1042')
  await expect(showcase.getByText('Preview 02 / 03')).toBeVisible()
  await nextPreview.click()
  await expect(showcase.locator('[aria-roledescription="slide"][aria-hidden="false"]')).toContainText('Stock')
  await expect(nextPreview).toBeDisabled()
  await previousPreview.focus()
  await page.keyboard.press('Enter')
  await expect(showcase.getByText('Preview 02 / 03')).toBeVisible()
  await page.getByRole('link', { name: /Try Free Trial/ }).first().click()
  await expect(page).toHaveURL(/\/auth\/register$/)
  await expect(page.getByRole('heading', { level: 1 })).toHaveText('Your next chapter starts here.')
  await page.getByRole('link', { name: 'View sign-in page' }).click()
  await expect(page).toHaveURL(/\/auth\/login$/)
  expect(errors).toEqual([])
})

for (const width of [375, 768, 1440]) {
  test(`responsive layout has no horizontal overflow at ${width}px`, async ({ page }) => {
    await page.setViewportSize({ width, height: 900 })
    await page.goto('/')
    const dimensions = await page.evaluate(() => ({ scroll: document.documentElement.scrollWidth, client: document.documentElement.clientWidth }))
    expect(dimensions.scroll).toBeLessThanOrEqual(dimensions.client)
    await expect(page.getByRole('link', { name: /Try Free Trial/ }).first()).toBeVisible()
  })
}

test('mobile menu and reduced motion remain usable', async ({ page }) => {
  await page.setViewportSize({ width: 375, height: 812 })
  await page.emulateMedia({ reducedMotion: 'reduce' })
  await page.goto('/')
  await page.getByRole('button', { name: 'Open menu' }).click()
  await expect(page.getByRole('dialog')).toBeVisible()
  const menu = await page.getByRole('dialog').boundingBox()
  expect(menu.x).toBeGreaterThanOrEqual(0)
  expect(menu.x + menu.width).toBeLessThanOrEqual(375)
  await page.getByRole('navigation', { name: 'Mobile navigation' }).getByRole('link', { name: 'Features' }).click()
  await expect(page.getByRole('dialog')).toHaveCount(0)
  await expect(page).toHaveURL(/#features$/)
})
