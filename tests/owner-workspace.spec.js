import { expect, test } from '@playwright/test'

const key = 'smartomni.owner-workspace-demo.v1'
async function login(page, role = 'owner') {
  await page.goto('/auth/login')
  await page.getByLabel('Email address').fill(`${role}@smartomni.demo`)
  await page.getByLabel('Password', { exact: true }).fill('Demo@123')
  await page.getByRole('button', { name: 'Sign in', exact: true }).click()
  await expect(page).toHaveURL(role === 'admin' ? /\/admin$/ : /\/merchant\/dashboard$/)
}
const table = (page, label) => page.getByLabel(label, { exact: true }).getByRole('table')

