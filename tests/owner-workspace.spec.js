test('staff cannot load new owner screens or execute owner business actions, and failed writes stay visible', async ({ page, context }) => {
  await login(page, 'staff')
  const loaded = []
  page.on('request', request => loaded.push(request.url()))
  for (const screen of ['subscription', 'vouchers', 'profit', 'logs']) { await page.goto(`/merchant/${screen}`); await expect(page).toHaveURL(/\/merchant\/dashboard$/) }
  expect(loaded.some(url => /OwnerConsole|BillingWorkspace|ownerWorkspaceStore/.test(url))).toBe(false)
  const denied = await page.evaluate(async () => { const { changeOwnerPlan } = await import('/src/features/portal/lib/ownerWorkspaceStore.js'); try { changeOwnerPlan('Free'); return 'Unexpected success' } catch (error) { return error.message } })
  expect(denied).toContain('Only the Tenant Owner')
  const owner = await context.newPage()
  await login(owner)
  await owner.goto('/merchant/subscription')
  await owner.getByRole('button', { name: 'Switch to Free in demo' }).click()
  await owner.evaluate(() => { Storage.prototype.setItem = () => { throw new Error('Storage blocked') } })
  await owner.getByRole('dialog').getByRole('button', { name: 'Apply demo plan' }).click()
  await expect(owner.getByRole('dialog').getByRole('alert')).toContainText('Could not save')
})

