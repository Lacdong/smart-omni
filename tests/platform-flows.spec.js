test('security events capture failed login and denied access without credentials, then filter and export', async ({ page }) => {
  await page.goto('/auth/login')
  await page.getByLabel('Email address').fill('private-input@example.com')
  await page.getByLabel('Password', { exact: true }).fill('secret-not-to-log')
  await page.getByRole('button', { name: 'Sign in', exact: true }).click()
  await expect(page.getByRole('status')).toContainText('incorrect')
  await login(page, 'owner')
  await page.goto('/admin/security')
  await expect(page).toHaveURL(/\/merchant\/dashboard$/)
  await page.getByRole('button', { name: 'Sign out', exact: true }).filter({ visible: true }).click()
  await login(page)
  await page.goto('/admin/security?type=ACCESS_DENIED')
  await expect(page.getByRole('button', { name: 'Access denied', exact: true })).toHaveCount(2)
  await page.getByRole('region', { name: 'Security events' }).getByRole('button', { name: 'Access denied' }).first().click()
  await expect(page.getByRole('dialog')).toContainText('Tenant Owner demo')
  await page.getByRole('button', { name: 'Close', exact: true }).click()
  const download = page.waitForEvent('download')
  await page.getByRole('button', { name: 'Export security log' }).click()
  expect((await download).suggestedFilename()).toBe('smartomni-security-events-demo.csv')
  const events = await page.evaluate(() => localStorage.getItem('smartomni.security-demo.v1'))
  expect(events).not.toContain('secret-not-to-log')
  expect(events).not.toContain('private-input@example.com')
  expect(events).not.toContain('Demo@123')
  expect(events).toContain('LOGIN_FAILURE')
  expect(events).toContain('ACCESS_DENIED')
})

