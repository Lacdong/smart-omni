import { expect, test } from '@playwright/test'
import { initialAudit, initialPlans, initialTenants } from '../src/features/platform/data/platformFixtures'

async function login(page, role = 'admin') {
  await page.goto('/auth/login')
  await page.getByLabel('Email address').fill(`${role}@smartomni.demo`)
  await page.getByLabel('Password', { exact: true }).fill('Demo@123')
  await page.getByRole('button', { name: 'Sign in', exact: true }).click()
  await expect(page.getByRole('heading', { name: role === 'admin' ? 'Platform overview' : 'Your store at a glance.', exact: true })).toBeVisible()
}

test('plan features update live merchant access, persist and record both action and security history', async ({ page, context }) => {
  await login(page)
  const owner = await context.newPage()
  await owner.goto('/auth/login')
  await owner.evaluate(() => sessionStorage.setItem('smartomni.demo-session', 'demo-owner'))
  await owner.goto('/merchant/dashboard')
  await expect(owner.getByRole('button', { name: 'Export report' })).toBeEnabled()
  await page.goto('/admin/plans')
  await page.getByRole('button', { name: 'Configure Pro features' }).click()
  for (const label of ['Report export', 'Inventory alerts', 'Workspace activity']) {
    const toggle = page.getByRole('switch', { name: label, exact: true })
    await expect(toggle).toBeChecked()
    await toggle.click()
  }
  await page.getByRole('button', { name: 'Save features' }).click()
  await expect(page.getByRole('dialog')).toBeVisible()
  await page.getByLabel('Reason', { exact: true }).fill('Verify feature availability across merchant sessions.')
  await page.getByRole('button', { name: 'Save features' }).click()
  await expect(page.getByRole('dialog')).toHaveCount(0)
  await expect(owner.getByRole('button', { name: 'Export report' })).toBeDisabled()
  await expect(owner.getByRole('heading', { name: 'Inventory needs attention' })).toHaveCount(0)
  await expect(owner.getByRole('heading', { name: 'Recent activity' })).toHaveCount(0)
  await expect(owner.getByRole('link', { name: 'Inventory alerts', exact: true })).toHaveCount(0)
  await owner.reload()
  await expect(owner.getByRole('button', { name: 'Export report' })).toBeDisabled()
  await page.reload()
  await page.getByRole('button', { name: 'Configure Pro features' }).click()
  await expect(page.getByRole('switch', { name: 'Report export', exact: true })).not.toBeChecked()
  for (const label of ['Report export', 'Inventory alerts', 'Workspace activity']) await page.getByRole('switch', { name: label, exact: true }).click()
  await page.getByLabel('Reason', { exact: true }).fill('Restore all Pro features for the demo.')
  await page.getByRole('button', { name: 'Save features' }).click()
  await expect(owner.getByRole('button', { name: 'Export report' })).toBeEnabled()
  await expect(owner.getByRole('heading', { name: 'Inventory needs attention' })).toBeVisible()
  await page.goto('/admin/audit')
  await expect(page.getByRole('region', { name: 'Admin actions' }).getByText('Plan features updated', { exact: true })).toHaveCount(2)
  await page.goto('/admin/security?type=ENTITLEMENTS_CHANGED')
  await expect(page.getByRole('region', { name: 'Security events' }).getByRole('button', { name: 'Plan feature change' })).toHaveCount(2)
})

test('shop alert lifecycle requires notes, persists history, updates the shop and reaches a merchant session', async ({ page, context }) => {
  await login(page)
  await page.goto('/admin/shop-alerts?platform=tiktok&status=OPEN')
  await expect(page.getByRole('region', { name: 'Shop connection alerts' }).getByRole('article')).toHaveCount(2)
  await page.getByRole('link', { name: 'TikTok Shop authorization expired', exact: true }).click()
  await page.getByRole('button', { name: 'Acknowledge alert', exact: true }).click()
  await page.getByRole('dialog').getByRole('button', { name: 'Acknowledge alert', exact: true }).click()
  await expect(page.getByLabel('Action note')).toBeVisible()
  await page.getByLabel('Action note').fill('Contacting the owner about expired authorization.')
  await page.getByRole('dialog').getByRole('button', { name: 'Acknowledge alert', exact: true }).click()
  await expect(page.getByRole('dialog').getByText('Acknowledged', { exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Resolve in demo', exact: true }).click()
  await page.getByLabel('Action note').fill('Simulated owner authorization renewal completed.')
  await page.getByRole('dialog').getByRole('button', { name: 'Resolve in demo', exact: true }).click()
  await expect(page.getByRole('dialog').getByText('Resolved', { exact: true })).toBeVisible()
  await page.reload()
  await expect(page.getByRole('dialog').getByText('Simulated owner authorization renewal completed.')).toBeVisible()
  const owner = await context.newPage()
  await owner.goto('/auth/login')
  await owner.evaluate(() => sessionStorage.setItem('smartomni.demo-session', 'demo-owner'))
  await owner.goto('/merchant/dashboard')
  await expect(owner.locator('#channels').getByText('Needs attention', { exact: true })).toHaveCount(0)
  await page.getByRole('button', { name: 'Reopen in demo' }).click()
  await page.getByLabel('Action note').fill('Simulated authorization issue recurred.')
  await page.getByRole('dialog').getByRole('button', { name: 'Reopen in demo' }).click()
  await expect(owner.locator('#channels').getByText('Needs attention', { exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Close', exact: true }).click()
  await expect(page).toHaveURL(/platform=tiktok/)
  await page.goto('/admin/audit?q=authorization')
  await expect(page.getByRole('link', { name: 'TikTok Shop authorization expired' })).toHaveCount(3)
})

