import { expect, test } from '@playwright/test'

const store = '/store/everyday-studio'

test('catalog sphere animates automatically without playback controls', async ({ page }) => {
  await page.emulateMedia({ reducedMotion: 'reduce' })
  await page.goto(store)
  const sphere = page.getByRole('img', { name: 'Rotating three-dimensional sphere traced with luminous contours and moving particles', exact: true })
  await expect(sphere).toBeVisible()
  await expect.poll(() => sphere.evaluate(canvas => canvas.width)).toBeGreaterThan(0)
  const still = await sphere.evaluate(canvas => canvas.toDataURL())
  await expect.poll(() => sphere.evaluate((canvas, image) => canvas.toDataURL() !== image, still)).toBe(true)
  await expect(page.getByRole('button', { name: /sphere animation/ })).toHaveCount(0)
  await expect(page.getByText('CONSIDERED. CONNECTED. YOURS.', { exact: true })).toHaveCount(0)
})

test('public storefront supports search, URL filters and sorting without an account', async ({ page }) => {
  const errors = []
  page.on('pageerror', error => errors.push(error.message))
  await page.goto(store)
  await expect(page.getByRole('heading', { level: 1 })).toHaveText('LESS, BUT BETTER.')
  await expect(page.getByRole('region', { name: 'Products' }).getByRole('article')).toHaveCount(6)
  await expect(page.getByRole('link', { name: /Sign in|Login|Cart|Checkout/ })).toHaveCount(0)
  await page.getByRole('button', { name: 'Sort products' }).click()
  await page.getByRole('menuitem', { name: 'Price: low to high' }).click()
  await expect(page.getByRole('region', { name: 'Products' }).getByRole('article').first()).toContainText('Everyday Tote')
  await page.getByRole('button', { name: 'Search this store' }).click()
  await page.getByRole('searchbox', { name: 'Search products' }).fill('mouse')
  await page.getByRole('search', { name: 'Search this store' }).getByRole('button', { name: 'Search', exact: true }).click()
  await expect(page).toHaveURL(/q=mouse/)
  await expect(page.getByRole('region', { name: 'Products' }).getByRole('article')).toHaveCount(1)
  await page.reload()
  await expect(page.getByRole('region', { name: 'Products' }).getByRole('article')).toHaveCount(1)
  await page.getByRole('button', { name: 'Clear filters', exact: true }).click()
  await expect(page.getByRole('region', { name: 'Products' }).getByRole('article')).toHaveCount(6)
  await page.getByRole('button', { name: 'List view', exact: true }).click()
  await expect(page.getByRole('button', { name: 'List view', exact: true })).toHaveAttribute('aria-pressed', 'true')
  await expect(page).toHaveURL(/view=list/)
  expect(errors).toEqual([])
})

