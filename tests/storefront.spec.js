test('recently viewed persists, stays unique and excludes the current product', async ({ page }) => {
  await page.goto(`${store}/products/wireless-mouse`)
  const recent = page.getByRole('region', { name: 'Recently viewed', exact: true })
  await expect(recent.getByRole('article')).toHaveCount(0)
  await page.evaluate(() => localStorage.setItem('smartomni:everyday-studio:recently-viewed', '{bad json'))
  await page.reload()
  await expect(recent.getByRole('article')).toHaveCount(0)
  await expect.poll(() => page.evaluate(() => localStorage.getItem('smartomni:everyday-studio:recently-viewed'))).toContain('wireless-mouse')
  await page.goto(`${store}/products/studio-headphones`)
  await expect(recent.getByRole('article')).toHaveCount(1)
  await expect(recent.getByRole('article').first()).toContainText('Wireless Mouse')
  await page.reload()
  await expect(recent.getByRole('article')).toHaveCount(1)
  await page.goto(`${store}/products/wireless-mouse?sku=WM-BLK`)
  await expect(recent.getByRole('article')).toHaveCount(1)
  await expect(recent.getByRole('article').first()).toContainText('Studio Headphones')
  await recent.getByRole('link', { name: 'Studio Headphones', exact: true }).last().click()
  await expect(page.getByRole('heading', { level: 1 })).toHaveText('Studio Headphones')
  await page.goto(`${store}?category=workspace`)
  await expect(recent.getByRole('article')).toHaveCount(2)
  await expect(recent.getByRole('article').first()).toContainText('Studio Headphones')
  const section = await recent.boundingBox()
  const footer = await page.locator('footer').boundingBox()
  expect(section.y + section.height).toBeLessThanOrEqual(footer.y)
})

